'use client';

import { useEffect, useMemo, useState } from 'react';
import type { AggregatedSnapshot } from '@/lib/aggregator';
import { getRuleBasedInsights } from '@/lib/insights';

type InsightSource = 'ai' | 'rule-based';

interface InsightPanelProps {
  snapshot: AggregatedSnapshot;
}

/**
 * AI Insight Panel.
 *
 * Renders rule-based insights immediately (instant paint, never blocks the
 * demo), then asks /api/insight to upgrade them with an LLM. If the route
 * returns rule-based output — no key, network error, bad response — the panel
 * simply keeps what it already shows.
 */
export default function InsightPanel({ snapshot }: InsightPanelProps) {
  const ruleBased = useMemo(() => getRuleBasedInsights(snapshot), [snapshot]);
  const payload = useMemo(() => JSON.stringify(snapshot), [snapshot]);

  const [insights, setInsights] = useState<string[]>(ruleBased);
  const [source, setSource] = useState<InsightSource>('rule-based');
  const [pending, setPending] = useState(false);

  useEffect(() => {
    setInsights(ruleBased);
    setSource('rule-based');

    const controller = new AbortController();
    setPending(true);

    fetch('/api/insight', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ snapshot }),
      signal: controller.signal,
    })
      .then((response) => (response.ok ? response.json() : Promise.reject(new Error('bad response'))))
      .then((data: { insights?: string[]; source?: InsightSource }) => {
        if (Array.isArray(data.insights) && data.insights.length > 0) {
          setInsights(data.insights);
          setSource(data.source === 'ai' ? 'ai' : 'rule-based');
        }
      })
      .catch(() => {
        /* keep the rule-based insights already on screen */
      })
      .finally(() => setPending(false));

    return () => controller.abort();
    // `payload` captures every field of snapshot, so it is a safe dependency.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [payload]);

  return (
    <section className="rounded-2xl border border-indigo-200 bg-gradient-to-br from-indigo-50 via-white to-white p-5 shadow-sm dark:border-indigo-900 dark:from-indigo-950 dark:via-slate-900 dark:to-slate-900">
      <header className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          <span className="flex h-7 w-7 items-center justify-center rounded-lg bg-indigo-600 text-xs font-bold text-white dark:bg-indigo-500 dark:text-slate-950">
            AI
          </span>
          <h2 className="text-sm font-semibold text-slate-900 dark:text-slate-100">Insight panel</h2>
        </div>
        <span
          className={`rounded-full px-2 py-0.5 text-xs font-medium ${
            source === 'ai'
              ? 'bg-indigo-100 text-indigo-700 dark:bg-indigo-950 dark:text-indigo-300'
              : 'bg-slate-100 text-slate-500 dark:bg-slate-800 dark:text-slate-400'
          }`}
          title={
            source === 'ai'
              ? 'Generated by the configured LLM.'
              : 'Computed on-device from your data (no AI key configured, or the AI call failed).'
          }
        >
          {source === 'ai' ? 'AI-generated' : 'Rule-based fallback'}
          {pending && source === 'rule-based' ? ' · refining…' : ''}
        </span>
      </header>

      <ul className="mt-4 space-y-3">
        {insights.map((insight) => (
          <li key={insight} className="flex gap-3 text-sm leading-relaxed text-slate-700 dark:text-slate-300">
            <span aria-hidden className="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-indigo-500" />
            <span>{insight}</span>
          </li>
        ))}
      </ul>

      <p className="mt-4 border-t border-indigo-100 pt-3 text-xs text-slate-500 dark:border-indigo-900 dark:text-slate-400">
        Derived live from the aggregated dataset — toggle a source and these are recalculated.
      </p>
    </section>
  );
}
